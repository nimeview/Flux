//! `flux.lock`: the resolved path-dependency tree of a project, pinned by
//! content so a build can verify it is using exactly the recorded sources.
//!
//! Each entry is one package reached through `[dependencies]` (transitively):
//! its `[package] name`, its directory relative to the project root, and a
//! SHA-256 over its `flux.toml` and every `.fl` file in its directory
//! (hidden directories and `target/` excluded; CRLF line endings are hashed
//! as LF). Entries are sorted by path.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

use crate::manifest::{DependencySpec, PackageManifest};

pub const LOCK_FILE: &str = "flux.lock";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    /// Directory relative to the project root, with `/` separators.
    pub path: String,
    pub checksum: String,
}

/// What [`sync_lock`] did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LockStatus {
    /// The project declares no dependencies; no lock is needed.
    NoDependencies,
    UpToDate,
    /// The lock was created or rewritten.
    Written,
}

/// The locked packages of the project at `project_root`. Problems with a
/// dependency (a missing directory, an unreadable manifest) are skipped here:
/// module resolution reports them with a span in the offending `flux.toml`.
pub fn compute_lock(project_root: &Path) -> Result<Vec<LockedPackage>, String> {
    let root = canonical(project_root);
    let mut found: BTreeMap<String, LockedPackage> = BTreeMap::new();
    let mut pending = dependency_dirs(&root);
    while let Some(dir) = pending.pop() {
        if !dir.is_dir() {
            continue;
        }
        let dir = canonical(&dir);
        let rel = relative(&root, &dir);
        if found.contains_key(&rel) {
            continue;
        }
        let name = PackageManifest::load(&dir.join("flux.toml"))
            .map(|m| m.package.name)
            .unwrap_or_else(|_| {
                dir.file_name()
                    .map(|n| n.to_string_lossy().into_owned())
                    .unwrap_or_else(|| rel.clone())
            });
        found.insert(
            rel.clone(),
            LockedPackage {
                name,
                path: rel,
                checksum: package_checksum(&dir),
            },
        );
        pending.extend(dependency_dirs(&dir));
    }
    Ok(found.into_values().collect())
}

/// Direct dependencies of the project whose path does not exist.
pub fn missing_dependencies(project_root: &Path) -> Vec<PathBuf> {
    dependency_dirs(&canonical(project_root))
        .into_iter()
        .filter(|dir| !dir.is_dir())
        .collect()
}

/// Brings `flux.lock` in line with the dependency tree. With `locked`, the
/// file is never written: a missing or different lock is an `Err` naming
/// what differs.
pub fn sync_lock(project_root: &Path, locked: bool) -> Result<LockStatus, String> {
    let packages = compute_lock(project_root)?;
    let lock_path = project_root.join(LOCK_FILE);
    if packages.is_empty() && !lock_path.exists() {
        return Ok(LockStatus::NoDependencies);
    }
    let wanted = render(&packages);
    let current = fs::read_to_string(&lock_path).ok();
    if current.as_deref() == Some(wanted.as_str()) {
        return Ok(LockStatus::UpToDate);
    }
    if locked {
        return Err(match current {
            None => format!("{LOCK_FILE} is missing; run without --locked to create it"),
            Some(text) => format!(
                "{LOCK_FILE} is out of date ({}); run without --locked to update it",
                describe_drift(&parse(&text), &packages)
            ),
        });
    }
    fs::write(&lock_path, wanted).map_err(|e| format!("cannot write {LOCK_FILE}: {e}"))?;
    Ok(LockStatus::Written)
}

fn render(packages: &[LockedPackage]) -> String {
    let mut out =
        String::from("# Generated by flux. Commit it; do not edit by hand.\nversion = 1\n");
    for p in packages {
        out.push_str(&format!(
            "\n[[package]]\nname = \"{}\"\npath = \"{}\"\nchecksum = \"{}\"\n",
            p.name, p.path, p.checksum
        ));
    }
    out
}

/// Best-effort read of a lock written by [`render`] (for drift messages).
fn parse(text: &str) -> Vec<LockedPackage> {
    let mut out = Vec::new();
    let mut current: Option<LockedPackage> = None;
    let value = |line: &str, key: &str| {
        line.strip_prefix(key)
            .and_then(|rest| rest.trim().strip_prefix('='))
            .map(|v| v.trim().trim_matches('"').to_string())
    };
    for line in text.lines().map(str::trim) {
        if line == "[[package]]" {
            out.extend(current.take());
            current = Some(LockedPackage {
                name: String::new(),
                path: String::new(),
                checksum: String::new(),
            });
        } else if let Some(p) = current.as_mut() {
            if let Some(v) = value(line, "name") {
                p.name = v;
            } else if let Some(v) = value(line, "path") {
                p.path = v;
            } else if let Some(v) = value(line, "checksum") {
                p.checksum = v;
            }
        }
    }
    out.extend(current);
    out
}

fn describe_drift(old: &[LockedPackage], new: &[LockedPackage]) -> String {
    let mut notes = Vec::new();
    for p in new {
        match old.iter().find(|o| o.path == p.path) {
            None => notes.push(format!("`{}` added", p.name)),
            Some(o) if o.checksum != p.checksum => notes.push(format!("`{}` changed", p.name)),
            Some(_) => {}
        }
    }
    for o in old {
        if !new.iter().any(|p| p.path == o.path) {
            notes.push(format!("`{}` removed", o.name));
        }
    }
    if notes.is_empty() {
        "format differs".into()
    } else {
        notes.join(", ")
    }
}

fn dependency_dirs(package_dir: &Path) -> Vec<PathBuf> {
    let Ok(manifest) = PackageManifest::load(&package_dir.join("flux.toml")) else {
        return Vec::new();
    };
    let mut names: Vec<&String> = manifest.dependencies.keys().collect();
    names.sort();
    names
        .into_iter()
        .filter_map(|name| match &manifest.dependencies[name] {
            DependencySpec::Path { path } => Some(package_dir.join(path)),
            DependencySpec::Version(_) => None,
        })
        .collect()
}

fn package_checksum(dir: &Path) -> String {
    let mut files = Vec::new();
    collect_package_files(dir, &mut files);
    files.sort();
    let mut hasher = Sha256::new();
    for file in files {
        hasher.update(relative(dir, &file).as_bytes());
        hasher.update([0]);
        hasher.update(normalize_newlines(fs::read(&file).unwrap_or_default()));
        hasher.update([0]);
    }
    format!("sha256:{:x}", hasher.finalize())
}

/// `\r\n` → `\n`, so a checkout with CRLF line endings (e.g. Git's
/// `core.autocrlf` on Windows) has the same checksum as an LF one.
fn normalize_newlines(bytes: Vec<u8>) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    let mut iter = bytes.into_iter().peekable();
    while let Some(b) = iter.next() {
        if b == b'\r' && iter.peek() == Some(&b'\n') {
            continue;
        }
        out.push(b);
    }
    out
}

fn collect_package_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if path.is_dir() {
            if !name.starts_with('.') && name != "target" {
                collect_package_files(&path, out);
            }
        } else if name == "flux.toml" || name.ends_with(".fl") {
            out.push(path);
        }
    }
}

fn canonical(path: &Path) -> PathBuf {
    path.canonicalize().unwrap_or_else(|_| path.to_path_buf())
}

/// `to` relative to `from` with `/` separators (`..` where needed).
fn relative(from: &Path, to: &Path) -> String {
    let from: Vec<_> = from.components().collect();
    let to: Vec<_> = to.components().collect();
    let common = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut parts: Vec<String> = vec!["..".into(); from.len() - common];
    parts.extend(
        to[common..]
            .iter()
            .map(|c| c.as_os_str().to_string_lossy().into_owned()),
    );
    if parts.is_empty() {
        ".".into()
    } else {
        parts.join("/")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn crlf_and_lf_checkouts_hash_the_same() {
        let lf = tempfile_dir("lf");
        let crlf = tempfile_dir("crlf");
        fs::write(lf.join("flux.toml"), "[package]\nname = \"p\"\n").unwrap();
        fs::write(lf.join("lib.fl"), "pub fn f() -> Int { 1 }\n").unwrap();
        fs::write(crlf.join("flux.toml"), "[package]\r\nname = \"p\"\r\n").unwrap();
        fs::write(crlf.join("lib.fl"), "pub fn f() -> Int { 1 }\r\n").unwrap();
        assert_eq!(package_checksum(&lf), package_checksum(&crlf));
        fs::write(crlf.join("lib.fl"), "pub fn f() -> Int { 2 }\r\n").unwrap();
        assert_ne!(package_checksum(&lf), package_checksum(&crlf));
        let _ = fs::remove_dir_all(lf);
        let _ = fs::remove_dir_all(crlf);
    }

    fn tempfile_dir(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("flux_lock_{tag}_{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }
}
